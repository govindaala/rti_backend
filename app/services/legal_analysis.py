"""दोनों पक्षों के लिए निष्पक्ष, स्रोत-आधारित विश्लेषण निर्देश."""

from enum import Enum


class AnalysisRole(str, Enum):
    """विश्लेषण का दृष्टिकोण; कानूनी तथ्य दोनों के लिए समान रहेंगे."""

    APPLICANT = "applicant"
    PIO = "pio"


COMMON_RULES = (
    "केवल उपलब्ध कानून, आधिकारिक स्रोत और उद्धृत निर्णयों पर निष्कर्ष दें।",
    "किसी भी धारा, निर्णय, पैरा या तथ्य का आविष्कार न करें।",
    "जहाँ स्रोत उपलब्ध नहीं है वहाँ स्पष्ट रूप से अनिश्चितता बताएँ।",
    "हर कानूनी मुद्दे का अलग विश्लेषण करें; पूरे निर्णय को एक पक्ष की जीत न मानें।",
    "अन्य लागू अपवाद, proviso, severability और बाध्यकारी उच्चतर निर्णय जाँचें।",
)


ROLE_GUIDANCE = {
    AnalysisRole.APPLICANT: (
        "आवेदक के वैध सूचना-अधिकार, माँगी गई सूचना, PIO के कारण, "
        "अपवाद की लागू होने की शर्तें और उपलब्ध वैधानिक उपायों का विश्लेषण करें। "
        "कमजोर या अप्रमाणित तर्क को स्पष्ट रूप से कमजोर बताएँ।"
    ),
    AnalysisRole.PIO: (
        "PIO के वैधानिक कर्तव्य, लागू अपवाद, अपवाद के प्रत्येक आवश्यक तत्व, "
        "रिकॉर्ड के पृथक्करण/आंशिक प्रकटीकरण और समय-सीमा का विश्लेषण करें। "
        "किसी वैध सूचना को रोकने के लिए झूठा या बनावटी आधार न सुझाएँ।"
    ),
}


def build_analysis_instructions(role: AnalysisRole) -> str:
    """चयनित भूमिका के निर्देशों को समान कानूनी निष्पक्षता के साथ जोड़ें."""
    rules = "\n".join(f"- {rule}" for rule in COMMON_RULES)
    return (
        f"भूमिका: {role.value}\n"
        f"भूमिका-विशिष्ट निर्देश: {ROLE_GUIDANCE[role]}\n"
        f"सभी मामलों में अनिवार्य नियम:\n{rules}"
    )
